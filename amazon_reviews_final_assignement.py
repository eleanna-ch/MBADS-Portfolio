from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.cluster import KMeans
import matplotlib.pyplot as plt

def plot_elbow_and_cluster(df_subset, sentiment_name, k=3):
    # Vectorize
    tfidf = TfidfVectorizer(stop_words='english', max_features=5000)
    X = tfidf.fit_transform(df_subset['Reviews'].astype(str))

    # --- Elbow Method ---
    inertias = []
    K_range = range(1, 11)
    print(f"Calculating Elbow Curve for {sentiment_name}...")
    for i in K_range:
        km = KMeans(n_clusters=i, random_state=42, n_init='auto')
        km.fit(X)
        inertias.append(km.inertia_)

    plt.figure(figsize=(8, 4))
    plt.plot(K_range, inertias, 'bx-')
    plt.xlabel('Number of Clusters (k)')
    plt.ylabel('Inertia')
    plt.title(f'Elbow Method for {sentiment_name}')
    plt.grid(True)
    plt.show()

    # --- Clustering ---
    print(f"\nRunning K-Means for {sentiment_name} with k={k}...")
    kmeans = KMeans(n_clusters=k, random_state=42, n_init='auto')
    kmeans.fit(X)

    # Print Top Terms
    feature_names = tfidf.get_feature_names_out()
    for topic_idx, topic in enumerate(kmeans.cluster_centers_):
        top_features = [feature_names[i] for i in topic.argsort()[:-11:-1]]
        print(f"Cluster {topic_idx}: {', '.join(top_features)}")
    print("-"*50)


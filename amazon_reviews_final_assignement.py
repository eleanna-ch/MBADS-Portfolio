def get_mean_bert_embeddings_batched(texts, tokenizer, model, batch_size=32, max_length=128):
    embeddings = []
    for i in tqdm(range(0, len(texts), batch_size), desc="Processing batches for mean pooling"):
        batch_texts = texts[i : i + batch_size]

        # Tokenization
        tokens = tokenizer(
            batch_texts,
            padding=True,
            truncation=True,
            return_tensors="tf",
            max_length=max_length
        )

        # Inference to get hidden states
        outputs = model(**tokens, training=False)
        last_hidden_state = outputs.last_hidden_state

        # Create attention mask to identify non-padding tokens
        attention_mask = tf.cast(tokens["attention_mask"], tf.float32)
        attention_mask = tf.expand_dims(attention_mask, axis=-1) # Expand mask to match hidden state dimensions

        # Multiply hidden states by the attention mask to zero out padding token embeddings
        masked_embeddings = last_hidden_state * attention_mask

        # Calculate sum of masked embeddings along the token dimension (axis=1)
        sum_masked_embeddings = tf.reduce_sum(masked_embeddings, axis=1)

        # Calculate sum of attention mask along the token dimension (axis=1)
        # Ensure minimum value of 1 to avoid division by zero
        sum_attention_mask = tf.maximum(tf.reduce_sum(attention_mask, axis=1), 1e-9)

        # Divide summed embeddings by summed mask to get mean-pooled embeddings
        mean_pooled_embeddings = sum_masked_embeddings / sum_attention_mask

        embeddings.append(mean_pooled_embeddings.numpy())

    if embeddings:
        return np.vstack(embeddings)
    else:
        return np.array([])


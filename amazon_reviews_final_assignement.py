freqs = sorted(freqs, key=lambda x: x[1], reverse=True)

# Select the top 12 most frequent terms from our whitelist
top_features = [f[0] for f in freqs if f[1] > 0][:12]

print(f"Final Whitelisted Top Features:\n{top_features}\n")

# Initialize Cluster Label column in the main dataframe
df['Cluster_Label'] = None

# 3. Cluster and Plot Function (Modified to Save Labels)
def cluster_and_plot_heatmap(df_subset, title, n_clusters=5, prefix="Clust"):
    # Vectorize using ONLY the selected top features
    cv = CountVectorizer(vocabulary=top_features)
    X = cv.fit_transform(df_subset['Reviews'].astype(str))
    feature_names = cv.get_feature_names_out()

    # Fit K-Means
    kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init='auto')
    kmeans.fit(X)

    # --- SAVE LABELS TO MAIN DATAFRAME ---
    # We use the index of df_subset to update the correct rows in the main df
    labels = [f"{prefix}_{i}" for i in kmeans.labels_]
    df.loc[df_subset.index, 'Cluster_Label'] = labels

    # Get Cluster Centers (Centroids)
    centers = kmeans.cluster_centers_

    # Create a DataFrame for the heatmap
    df_centers = pd.DataFrame(centers, columns=feature_names)
    df_centers.index = [f"Cluster {i}" for i in range(n_clusters)]

    # Plot Heatmap
    plt.figure(figsize=(14, 6))
    sns.heatmap(df_centers, cmap='Greys', annot=True, fmt=".2f")
    plt.title(f"{title} - Topic Cluster Centroids (HW/SW Whitelist)")
    plt.xlabel("Hardware/Software Keywords")
    plt.ylabel("Clusters")
    plt.show()

    # Statistics
    df_clustered = df_subset.copy()
    df_clustered['Cluster'] = kmeans.labels_

    print(f"\nCluster Statistics ({title}):")
    print("-" * 60)
    for i in range(n_clusters):
        cluster_data = df_clustered[df_clustered['Cluster'] == i]
        if not cluster_data.empty:
            median_rate = cluster_data['Rating'].median()
            valid_brands = cluster_data['Brand Name'].dropna()
            brand_str = "No Brand Data"
            if not valid_brands.empty:
                top_brand = valid_brands.value_counts().idxmax()
                count = valid_brands.value_counts().max()
                total = len(valid_brands)
                brand_str = f"{top_brand} ({count}/{total})"
            print(f"Cluster {i}: Median Rating = {median_rate} | Top Brand = {brand_str}")
    print("-" * 60)

# Run for Positive Reviews (k=5)

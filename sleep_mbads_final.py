# Discretize numeric columns into 3 bins: Low/Medium/High (simple)
def bin3(series, colname):
    # qcut makes bins with approx equal counts
    # duplicates='drop' avoids errors if many equal values
    binned = pd.qcut(series, q=3, duplicates="drop", labels=["Low", "Med", "High"])
    return colname + "=" + binned.astype(str)


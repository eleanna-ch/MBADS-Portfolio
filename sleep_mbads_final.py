"""Apriori"""

def support_count(itemset, transactions):
    """Count how many transactions contain the itemset."""
    count = 0
    itemset = set(itemset)
    for t in transactions:
        if itemset.issubset(set(t)):
            count += 1
    return count

def apriori(transactions, min_support=0.10):
    """
    Returns frequent itemsets with support >= min_support.
    Output: dict {frozenset(items): support}
    """
    n = len(transactions)
    # C1: all single items
    items = sorted(list(set([item for t in transactions for item in t])))
    L = {}
    Lk = {}

    # L1
    for it in items:
        c = support_count([it], transactions)
        sup = c / n
        if sup >= min_support:
            Lk[frozenset([it])] = sup

    L.update(Lk)
    k = 2

    while len(Lk) > 0:
        # generate candidates Ck from Lk-1
        prev_itemsets = list(Lk.keys())
        candidates = set()

        for i in range(len(prev_itemsets)):
            for j in range(i+1, len(prev_itemsets)):
                union = prev_itemsets[i].union(prev_itemsets[j])
                if len(union) == k:
                    candidates.add(union)

        # count supports for candidates
        Lk_new = {}
        for cand in candidates:
            c = support_count(list(cand), transactions)
            sup = c / n
            if sup >= min_support:
                Lk_new[frozenset(cand)] = sup

        L.update(Lk_new)
        Lk = Lk_new
        k += 1

    return L

def generate_rules(freq_itemsets, min_conf=0.6):
    """
    Create association rules from frequent itemsets.
    Rule: A -> B
    Compute support(A∪B), confidence, lift
    Returns list of dict rules.
    """
    rules = []
    for itemset, sup_ab in freq_itemsets.items():
        if len(itemset) < 2:
            continue

        items = list(itemset)
        # all possible splits A/B
        for i in range(1, len(items)):
            # simple split generation using combinations
            from itertools import combinations
            for A in combinations(items, i):
                A = frozenset(A)
                B = itemset.difference(A)

                sup_a = freq_itemsets.get(A, None)
                sup_b = freq_itemsets.get(B, None)

                # If not in dictionary, skip (usually ok because B might not be frequent alone)
                if sup_a is None or sup_a == 0:
                    continue

                conf = sup_ab / sup_a

                # Lift needs support(B). If B is not frequent alone, compute directly (simple)
                if sup_b is None:
                    sup_b = support_count(list(B), transactions) / len(transactions)

                if sup_b == 0:
                    continue

                lift = conf / sup_b

                if conf >= min_conf:
                    rules.append({
                        "A": A,
                        "B": B,
                        "support": sup_ab,
                        "confidence": conf,
                        "lift": lift
                    })

    # sort by lift then confidence
    rules = sorted(rules, key=lambda x: (x["lift"], x["confidence"]), reverse=True)
    return rules

